package com.jesty.rpchargingseparation;

import android.content.SharedPreferences;

/** Records only new temperature extremes from existing power-telemetry samples. */
final class BatteryTemperatureHistory {
    private static final String MIN_KEY = "battery_temp_min_tenths";
    private static final String MAX_KEY = "battery_temp_max_tenths";
    private static final Object LOCK = new Object();

    private BatteryTemperatureHistory() { }

    static BatteryTemperatureExtremes read(SharedPreferences preferences) {
        synchronized (LOCK) {
            return new BatteryTemperatureExtremes(
                    preferences.getInt(MIN_KEY, BatteryTemperatureExtremes.EMPTY_MIN),
                    preferences.getInt(MAX_KEY, BatteryTemperatureExtremes.EMPTY_MAX));
        }
    }

    static BatteryTemperatureExtremes record(SharedPreferences preferences, float celsius) {
        synchronized (LOCK) {
            BatteryTemperatureExtremes previous = read(preferences);
            BatteryTemperatureExtremes next = previous.observe(celsius);
            if (next != previous) {
                // apply() updates the in-memory snapshot immediately, with async disk IO.
                // No storage writes are generated by ordinary, unchanged readings.
                preferences.edit().putInt(MIN_KEY, next.minTenths)
                        .putInt(MAX_KEY, next.maxTenths).apply();
            }
            return next;
        }
    }

    static void reset(SharedPreferences preferences) {
        synchronized (LOCK) {
            preferences.edit().remove(MIN_KEY).remove(MAX_KEY).apply();
        }
    }
}
